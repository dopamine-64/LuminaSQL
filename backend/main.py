# /ask  — kept for backwards compatibility, calls both internally
# ---------------------------------------------------------------
@app.post("/ask")
def ask(data: AskRequest):
    try:
        engine = create_db_engine(
            data.host, data.port, data.username, data.password, data.database
        )

        if not test_connection(engine):
            return JSONResponse(status_code=400, content={
                "sql":         "",
                "result":      "Database connection failed. Check your credentials.",
                "explanation": "",
                "fixed":       False
            })

        key = data.user_api_key

        # Single API call: gets SQL + explanation together instead of
        # two separate requests.
        gen = generate_sql_and_explanation(data.question, engine, key)
        sql = clean_sql(gen["sql"])
        explanation = gen["explanation"]

        result = run_query(sql, engine)
        fixed  = False

        if isinstance(result, dict) and "error" in result:
            # Fixing still needs its own call — we don't know the fix
            # will work until we try it, so it can't be pre-merged.
            fixed_sql    = clean_sql(fix_sql(data.question, sql, result["error"], engine, key))
            retry_result = run_query(fixed_sql, engine)

            if not (isinstance(retry_result, dict) and "error" in retry_result):
                sql    = fixed_sql
                result = retry_result
                fixed  = True
                # Explanation from the original (failed) SQL no longer
                # applies — get a fresh one for the fixed query.
                explanation = explain_sql(sql, key)
            else:
                return JSONResponse(status_code=200, content={
                    "sql":         fixed_sql,
                    "result":      retry_result,
                    "explanation": f"Query failed and auto-fix also failed. Error: {retry_result['error']}",
                    "fixed":       False
                })

        return {
            "sql":         sql,
            "result":      result,
            "explanation": explanation,
            "fixed":       fixed
        }

    except Exception as e:
        print(f"❌ /ask crash: {e}")
        return JSONResponse(status_code=500, content={
            "sql":         "",
            "result":      "Server error",
            "explanation": str(e),
            "fixed":       False
        })


